function load(file) {
  const code = buildSync({ entryPoints: [file], bundle: true, write: false, platform: 'node', format: 'cjs', external: ['react'] }).outputFiles[0].text;
  const context = { module: { exports: {} }, require, localStorage, console, URL };
  vm.runInNewContext(code, context);
  return context.module.exports;
}
